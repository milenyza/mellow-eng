function challenge(
  id: string,
  difficulty: SentenceChallenge['difficulty'],
  topics: readonly [SentenceTopic, ...SentenceTopic[]],
  prompt: string,
  sentence: string,
  feedback: string,
  reference: SentenceContentReference,
  extras: Pick<SentenceChallenge, 'distractors' | 'alternatives' | 'hint'> = {},
): SentenceChallenge {
  return {
    id,
    difficulty,
    topics,
    prompt,
    sentence,
    feedback,
    reference,
    ...extras,
  }
}

